"""Extract the pinned Telegram path routine verbatim; no Android build or APK."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path('vendor/telegram/TMessagesProj/src/main/java/org/telegram/ui/ActionBar/MessageDrawable.java')
TARGET = Path('integration/ui-only/rendering/src/main/java/dev/themestudio/rendering/UpstreamBubblePath.java')
SHA = 'f32ffeec763f0bdbf4bec25b52d654f77bff733d'


def routine(text):
    start = text.index('    private void generatePath(')
    opening = text.index('{', start)
    depth = 1
    end = opening + 1
    while depth:
        if text[end] == '{': depth += 1
        elif text[end] == '}': depth -= 1
        end += 1
    return text[start:end]


HEADER = '''// SPDX-License-Identifier: GPL-2.0-or-later
// Derived from DrKLO/Telegram MessageDrawable at __SHA__.
// generatePath is verbatim upstream. Surrounding adapter replaces client dependencies.
// Generated by scripts/extract_bubble_geometry.py. This is geometry, NOT a chat UI.
package dev.themestudio.rendering;

import android.graphics.Path;
import android.graphics.Rect;
import android.graphics.RectF;

/** UI-only original bubble geometry: no Theme, SharedConfig, accounts, JNI or network. */
public final class UpstreamBubblePath {
    public static final int TYPE_TEXT = 0;
    public static final int TYPE_MEDIA = 1;
    public static final int TYPE_PREVIEW = 2;

    private final float density;
    private final boolean isOut;
    private final int currentType;
    private final RectF rect = new RectF();
    private boolean isTopNear;
    private boolean isBottomNear;
    private boolean botButtonsBottom;
    private boolean drawFullBubble;
    private int topY;
    private int currentBackgroundHeight;

    public UpstreamBubblePath(float density, boolean outgoing, int type) {
        if (Float.isNaN(density) || Float.isInfinite(density) || density <= 0) {
            throw new IllegalArgumentException("Positive finite display density required");
        }
        if (type < TYPE_TEXT || type > TYPE_PREVIEW) throw new IllegalArgumentException("Unknown bubble type");
        this.density = density;
        this.isOut = outgoing;
        this.currentType = type;
    }

    /** Caller supplies layout state; no messenger configuration is read. UI thread only. */
    public void setLayoutState(boolean topNear, boolean bottomNear, boolean buttonsBottom,
            boolean fullBubble, int topY, int backgroundHeight) {
        isTopNear = topNear;
        isBottomNear = bottomNear;
        botButtonsBottom = buttonsBottom;
        drawFullBubble = fullBubble;
        this.topY = topY;
        currentBackgroundHeight = backgroundHeight;
    }

    /** All dimensions are original renderer pixel inputs, not invented layout defaults. */
    public void build(Path path, Rect bounds, int padding, int radius, int smallRadius,
            int nearRadius, int top, boolean fullBottom, boolean fullTop, boolean customPaint) {
        generatePath(path, bounds, padding, radius, smallRadius, nearRadius, top,
                fullBottom, fullTop, customPaint);
    }

    // Same TYPE_PREVIEW conversion as MessageDrawable.dp; AndroidUtilities.dp's
    // density is supplied explicitly rather than initializing the Telegram application.
    private int dp(float value) {
        if (currentType == TYPE_PREVIEW) return (int) Math.ceil(3 * value);
        if (value == 0) return 0;
        return (int) Math.ceil(density * value);
    }

'''

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
method = routine((ROOT / SOURCE).read_text())
content = HEADER.replace('__SHA__', SHA) + method + '\n}\n'
manifest = json.dumps({
    'upstream_commit': SHA, 'source': SOURCE.as_posix(), 'target': TARGET.as_posix(),
    'routine': 'generatePath', 'routine_sha256': hashlib.sha256(method.encode()).hexdigest(),
    'unchanged': 'generatePath body and signature',
    'adapter_changes': ['Explicit density instead of AndroidUtilities global',
                        'Explicit state instead of Theme/SharedConfig/client initialization'],
    'not_included': ['ChatMessageCell layout/text', 'bubble shadows/gradients/crossfades',
                     'screen UI', 'network/protocol', 'JNI'],
}, indent=2) + '\n'
manifest_path = ROOT / 'integration/ui-only/UPSTREAM.json'
if args.check:
    assert (ROOT / TARGET).read_text() == content, 'Extracted source drift; regenerate deliberately'
    assert manifest_path.read_text() == manifest, 'Provenance drift'
    print('PASS: generatePath exactly matches pinned upstream; adapter/provenance match generator.')
    print('Not an Android compilation, runtime or whole-interface identity test.')
else:
    (ROOT / TARGET).write_text(content)
    manifest_path.write_text(manifest)
